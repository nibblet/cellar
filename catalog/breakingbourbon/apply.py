#!/usr/bin/env python3
"""normalized.json (+ decisions.json) → import.sql, a single migration to review and apply.

decisions.json is optional: {"<canonical_url>": "<product_id>" | "new" | "skip"} settles the
proposed matches. Anything undecided stays out of the import.

Verified rows are never touched (the protect trigger would refuse anyway). Booleans, finish
and is_core_range only ever go up. New expressions land as status = draft; core-range ones
from makers already on the shelf are included, the rest hidden.
"""
import json, pathlib, re, subprocess, sys

HERE = pathlib.Path(__file__).parent
FACT_FIELDS = ["proof", "age_years", "age_label", "expression_type", "mash_style", "mash_bill", "spirit_type",
               "bottled_in_bond", "barrel_proof", "finish", "msrp_usd", "is_core_range"]
ENUM = {"expression_type": "cellar.expression_type", "mash_style": "cellar.mash_style", "spirit_type": "cellar.spirit_type"}

def q(v, field=None):
    if v is None: return "null"
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, (int, float)): return repr(v)
    if isinstance(v, list): return "ARRAY[" + ",".join(q(x) for x in v) + "]::text[]"
    s = "'" + str(v).replace("'", "''") + "'"
    return f"{s}::{ENUM[field]}" if field in ENUM else s

def slug(name):
    s = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return s[:60] or "maker"

def main():
    o = json.loads((HERE / "normalized.json").read_text())
    decisions = json.loads((HERE / "decisions.json").read_text()) if (HERE / "decisions.json").exists() else {}
    snap = json.loads((HERE / "catalog-snapshot.json").read_text())
    by_id = {p["id"]: p for p in snap["products"]}
    makers_with_included = {p["producer_id"] for p in snap["products"] if p["catalog_included"] and p["producer_id"]}
    sys.path.insert(0, str(HERE)); from normalize import diff_for

    # Settle proposals: {"<url>": "<product_id>" | "new" | "skip" | {"action": ..., "<field>": override}}
    decided_new, undecided = [], []
    for pr in o["proposed"]:
        d = decisions.get(pr["url"])
        if d is None: undecided.append(pr); continue
        action, overrides = (d, {}) if isinstance(d, str) else (d.get("action"), {k: v for k, v in d.items() if k != "action"})
        c = pr["data"]
        for k, v in overrides.items():
            if k in ("expression", "name"): c[k] = v
            else: c["facts"][k] = v
        if action == "skip": continue
        if action == "new":
            decided_new.append({**c, "catalog_included": c["facts"]["is_core_range"] and c["facts"]["maker_id"] in makers_with_included})
        elif action in by_id:
            p = by_id[action]
            o["matched"].append({"product_id": action, "product": p["name"], "how": "decided", "verified": p["verified"], "candidate": c, "diff": diff_for(p, c)})
    still_new = []
    for c in o["new"]:
        d = decisions.get(c["canonical_url"])
        if isinstance(d, str) and d in by_id:
            p = by_id[d]
            o["matched"].append({"product_id": d, "product": p["name"], "how": "decided", "verified": p["verified"], "candidate": c, "diff": diff_for(p, c)})
        elif d == "skip":
            continue
        else:
            still_new.append(c)
    o["new"] = still_new + decided_new
    o["proposed"] = undecided
    sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, cwd=HERE).stdout.strip()
    L = [f"-- Breaking Bourbon import, generated by catalog/breakingbourbon/apply.py from bb-reviews.json @ {sha}.",
         "-- One authoritative source for expression facts; verified rows untouched; new rows are drafts.",
         "", "alter table cellar.products add column if not exists source_url text;",
         "comment on column cellar.products.source_url is 'Where the facts came from (the canonical review page). Null = seeded before provenance was tracked.';", ""]

    # makers
    L.append("-- New makers")
    for m in o["new_makers"]:
        L.append(f"insert into cellar.makers (name, slug, type, owner, country) values ({q(m['name'])}, {q(slug(m['name']))}, 'bourbon', {q(m['owner'])}, 'US') on conflict (slug) do nothing;")
    maker_ref = {slug(m["name"]): f"(select id from cellar.makers where slug = {q(slug(m['name']))})" for m in o["new_makers"]}
    def maker_sql(f):
        if f["maker_id"]: return q(f["maker_id"]) + "::uuid"
        clean = re.sub(r"\s*\(.*?\)", "", f["distillery"] or "").strip()
        if not f["sourced"] and clean and slug(clean) in maker_ref: return maker_ref[slug(clean)]
        return "null"

    # matched updates
    L += ["", "-- Matched products: fills and replacements (BB wins on non-verified rows)"]
    n_upd = 0
    for m in o["matched"]:
        if m["verified"]: continue
        sets = [f"{d['field']} = {q(d['bb'], d['field'])}" for d in m["diff"] if d["action"] in ("fill", "replace") and (d["bb"] is not None or d["field"] == "expression")]
        if any(d["field"] == "expression_type" for d in m["diff"]) and "expression_type" in m["candidate"]["facts"]:
            pass
        if any(d["field"] == "age_years" for d in m["diff"] if d["action"] != "same"):
            sets.append(f"nas = ({q(m['candidate']['facts']['age_years'])} is null)")
        c = m["candidate"]
        sets.append(f"source_url = {q(c['canonical_url'])}")
        old_name = [d["catalog"] for d in m["diff"] if d["field"] == "name" and d["action"] != "same"]
        alias_add = c["aliases"] + old_name
        if alias_add:
            sets.append(f"aliases = (select array_agg(distinct x) from unnest(coalesce(aliases, '{{}}') || {q(alias_add)}) x)")
        L.append(f"update cellar.products set {', '.join(sets)} where id = {q(m['product_id'])}::uuid and facts_verified_at is null;")
        n_upd += 1

    # new rows: batched VALUES, guarded by the unique index's key
    L += ["", "-- New expressions (drafts; core range from makers already on the shelf is included)"]
    COLS = ["name", "brand_family", "expression", "producer", "producer_id", *FACT_FIELDS, "nas", "catalog_included", "aliases", "source_url"]
    rows = []
    for c in o["new"]:
        f = c["facts"]
        rows.append("(" + ", ".join([
            q(c["name"]), q(c["family"]), q(c["expression"]),
            q(f["maker_name"] or (None if f["sourced"] else f["distillery"])), maker_sql(f),
            *[q(f.get(k)) for k in FACT_FIELDS],
            q(f["age_years"] is None), q(c["catalog_included"]),
            q(c["aliases"]) if c["aliases"] else "null::text[]", q(c["canonical_url"]),
        ]) + ")")
    n_new = len(rows)
    for k in range(0, len(rows), 100):
        L.append(
            f"insert into cellar.products (type, status, source, specs, rarity, {', '.join(COLS)})\n"
            f"select 'bourbon', 'draft', 'seed', '{{}}'::jsonb, null, " + ", ".join(f"v.{c}::{ENUM[c]}" if c in ENUM else f"v.{c}" for c in COLS) + " from (values\n" + ",\n".join(rows[k:k+100]) + f"\n) as v({', '.join(COLS)})\n"
            "where not exists (select 1 from cellar.products p where p.type = 'bourbon' and p.merged_into is null\n"
            "  and coalesce(p.brand_family,'') = coalesce(v.brand_family,'') and coalesce(p.expression,'') = coalesce(v.expression,'') and coalesce(p.release_label,'') = '');"
        )
    L += ["", f"-- {n_upd} updates, {n_new} inserts, {len(o['new_makers'])} makers; {len(o['proposed'])} proposed matches left for decisions.json"]
    (HERE / "import.sql").write_text("\n".join(L))
    print(L[-1])

if __name__ == "__main__":
    main()
