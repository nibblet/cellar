#!/usr/bin/env python3
"""normalized.json (+ decisions.json) → import.sql, a single migration to review and apply.

decisions.json is optional: {"<canonical_url>": "<product_id>" | "new" | "skip"} settles the
proposed matches. Anything undecided stays out of the import.

Verified rows are never touched (the protect trigger would refuse anyway). Booleans, finish
and is_core_range only ever go up. New expressions land as status = draft; core-range ones
from makers already on the shelf are included, the rest hidden.
"""
import json, pathlib, re, subprocess

HERE = pathlib.Path(__file__).parent
FACT_FIELDS = ["proof", "age_years", "age_label", "expression_type", "mash_style", "mash_bill", "spirit_type",
               "bottled_in_bond", "barrel_proof", "finish", "msrp_usd", "is_core_range"]
ENUM = {"expression_type": "cellar.expression_type", "mash_style": "cellar.mash_style", "spirit_type": "cellar.spirit_type"}

def q(v, field=None):
    if v is None: return "null"
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, (int, float)): return repr(v)
    if isinstance(v, list): return "ARRAY[" + ",".join(q(x) for x in v) + "]::text[]"
    s = "'" + str(v).replace("'", "''") + "'"
    return f"{s}::{ENUM[field]}" if field in ENUM else s

def slug(name):
    s = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return s[:60] or "maker"

def main():
    o = json.loads((HERE / "normalized.json").read_text())
    decisions = json.loads((HERE / "decisions.json").read_text()) if (HERE / "decisions.json").exists() else {}
    sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, cwd=HERE).stdout.strip()
    L = [f"-- Breaking Bourbon import, generated by catalog/breakingbourbon/apply.py from bb-reviews.json @ {sha}.",
         "-- One authoritative source for expression facts; verified rows untouched; new rows are drafts.",
         "", "alter table cellar.products add column if not exists source_url text;",
         "comment on column cellar.products.source_url is 'Where the facts came from (the canonical review page). Null = seeded before provenance was tracked.';", ""]

    # makers
    L.append("-- New makers")
    for m in o["new_makers"]:
        L.append(f"insert into cellar.makers (name, slug, type, owner, country) values ({q(m['name'])}, {q(slug(m['name']))}, 'bourbon', {q(m['owner'])}, 'US') on conflict (slug) do nothing;")
    maker_ref = {slug(m["name"]): f"(select id from cellar.makers where slug = {q(slug(m['name']))})" for m in o["new_makers"]}
    def maker_sql(f):
        if f["maker_id"]: return q(f["maker_id"]) + "::uuid"
        if not f["sourced"] and f["distillery"] and slug(f["distillery"]) in maker_ref: return maker_ref[slug(f["distillery"])]
        return "null"

    # matched updates
    L += ["", "-- Matched products: fills and replacements (BB wins on non-verified rows)"]
    n_upd = 0
    settled = []
    for p in o["proposed"]:
        d = decisions.get(p["url"])
        if d and d not in ("new", "skip"):
            settled.append((d, p))
    for m in o["matched"]:
        if m["verified"]: continue
        sets = [f"{d['field']} = {q(d['bb'], d['field'])}" for d in m["diff"] if d["action"] in ("fill", "replace")]
        if any(d["field"] == "age_years" for d in m["diff"] if d["action"] != "same"):
            sets.append(f"nas = ({q(m['candidate']['facts']['age_years'])} is null)")
        c = m["candidate"]
        sets.append(f"source_url = {q(c['canonical_url'])}")
        if c["aliases"]:
            sets.append(f"aliases = (select array_agg(distinct x) from unnest(coalesce(aliases, '{{}}') || {q(c['aliases'])}) x)")
        L.append(f"update cellar.products set {', '.join(sets)} where id = {q(m['product_id'])}::uuid and facts_verified_at is null;")
        n_upd += 1

    # new rows
    L += ["", "-- New expressions (drafts; core range from makers already on the shelf is included)"]
    n_new = 0
    for c in o["new"]:
        f = c["facts"]
        cols = {
            "type": "'bourbon'", "name": q(c["name"]), "brand_family": q(c["family"]), "expression": q(c["expression"]),
            "producer": q(f["maker_name"] or (None if f["sourced"] else f["distillery"])), "producer_id": maker_sql(f),
            **{k: q(f.get(k), k) for k in FACT_FIELDS},
            "nas": q(f["age_years"] is None), "rarity": "null",
            "catalog_included": q(c["catalog_included"]), "status": "'draft'", "source": "'seed'",
            "aliases": q(c["aliases"]) if c["aliases"] else "null", "source_url": q(c["canonical_url"]), "specs": "'{}'::jsonb",
        }
        guard = (f"where not exists (select 1 from cellar.products where type = 'bourbon' and merged_into is null "
                 f"and coalesce(brand_family,'') = coalesce({q(c['family'])},'') and coalesce(expression,'') = coalesce({q(c['expression'])},'') and coalesce(release_label,'') = '')")
        L.append(f"insert into cellar.products ({', '.join(cols)}) select {', '.join(cols.values())} {guard};")
        n_new += 1
    L += ["", f"-- {n_upd} updates, {n_new} inserts, {len(o['new_makers'])} makers; {len(o['proposed'])} proposed matches left for decisions.json"]
    (HERE / "import.sql").write_text("\n".join(L))
    print(L[-1])

if __name__ == "__main__":
    main()
